CREATE TABLE `LoanEntry` (
    `id` VARCHAR(191) NOT NULL,
    `leadId` VARCHAR(191) NULL,
    `studentName` VARCHAR(191) NOT NULL,
    `phone` VARCHAR(191) NULL,
    `email` VARCHAR(191) NULL,
    `paymentFor` VARCHAR(191) NOT NULL,
    `paidOn` DATETIME(3) NOT NULL,
    `emiAmount` DOUBLE NOT NULL,
    `interestAmount` DOUBLE NOT NULL DEFAULT 0,
    `vinsupAmount` DOUBLE NOT NULL,
    `transactionId` VARCHAR(191) NULL,
    `lender` VARCHAR(191) NULL,
    `batch` VARCHAR(191) NULL,
    `mode` VARCHAR(191) NULL,
    `comments` TEXT NULL,
    `verified` BOOLEAN NOT NULL DEFAULT false,
    `verifiedById` VARCHAR(191) NULL,
    `verifiedAt` DATETIME(3) NULL,
    `createdById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    INDEX `LoanEntry_paidOn_idx`(`paidOn`),
    INDEX `LoanEntry_leadId_idx`(`leadId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE TABLE `JodoSettlement` (
    `id` VARCHAR(191) NOT NULL,
    `paymentRef` VARCHAR(191) NOT NULL,
    `leadId` VARCHAR(191) NULL,
    `jodoStudentId` VARCHAR(191) NULL,
    `studentName` VARCHAR(191) NOT NULL,
    `rollNumber` VARCHAR(191) NULL,
    `instituteName` VARCHAR(191) NULL,
    `stream` VARCHAR(191) NULL,
    `grade` VARCHAR(191) NULL,
    `product` VARCHAR(191) NULL,
    `payMode` VARCHAR(191) NULL,
    `amount` DOUBLE NOT NULL,
    `feeAmount` DOUBLE NULL,
    `paidDate` DATETIME(3) NULL,
    `settlementUtr` VARCHAR(191) NULL,
    `settlementBank` VARCHAR(191) NULL,
    `settlementDate` DATETIME(3) NULL,
    `phone` VARCHAR(191) NULL,
    `importedById` VARCHAR(191) NULL,
    `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),

    UNIQUE INDEX `JodoSettlement_paymentRef_key`(`paymentRef`),
    INDEX `JodoSettlement_paidDate_idx`(`paidDate`),
    INDEX `JodoSettlement_leadId_idx`(`leadId`),
    PRIMARY KEY (`id`)
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
